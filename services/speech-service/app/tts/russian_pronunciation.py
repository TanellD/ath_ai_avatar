"""Точечные подсказки ударения только для текста, отправляемого на синтез.

Это не универсальный расстановщик ударений. Неоднозначные слова без контекста
не исправляем; словарь пополняется по конкретным ошибкам произношения.
"""

import re

_ACUTE = "\u0301"
_WORD_RE = re.compile(r"[\w\u0300\u0301]+")

# Индекс ударной гласной (с нуля). Формы перечислены явно: замена подстрок
# могла бы затронуть другие слова, идентификаторы или незнакомые производные.
_STRESS = {
    **dict.fromkeys(
        ("эпитет", "эпитета", "эпитету", "эпитетом", "эпитете",
         "эпитеты", "эпитетов", "эпитетам", "эпитетами", "эпитетах"),
        2,
    ),
    "охуенно": 3,
}


def with_russian_stress(text: str) -> str:
    """Сохранить регистр, пунктуацию и уже заданные ударения."""
    def replace(match: re.Match[str]) -> str:
        word = match.group()
        index = _STRESS.get(word.lower())
        if index is None:
            return word
        return word[:index + 1] + _ACUTE + word[index + 1:]

    return _WORD_RE.sub(replace, text)

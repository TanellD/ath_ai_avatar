/**
 * Локальная остановка при перебивании — Claude.md §6, шаг 1.
 *
 * Это самая важная функция клиента и единственная точка, из которой
 * останавливается воспроизведение.
 *
 *   «Клиент, VAD, onset речи → немедленно и локально: audio.pause(), очистка
 *    очереди буферов, сброс кадров мимики, фиксация субтитров на текущей
 *    позиции. Без сетевого round-trip — именно это укладывается в метрику 3.»
 *
 * Отдельного оверлея субтитров больше нет — тот же текст читается в чате
 * слева, — но «фиксация на текущей позиции» осталась требованием: реплика в
 * чате собирается из токенов, а они обгоняют звук, и без обрезки сотрудник
 * прочитал бы фразу, которую не слышал.
 *
 * **У функции уже два вызывающих: отправка текста (handleSend) и голосовой
 * onset (handleVoiceStart, сейчас push-to-talk, а не мгновенный VAD-onset —
 * см. docs/PROJECT_DESCRIPTION.md). Функция от способа ввода не зависит.**
 * Ровно поэтому она вынесена отдельно от обоих обработчиков — общая точка
 * остановки, а не две реализации, которые могли бы разъехаться и одна из
 * них забыла бы, например, зафиксировать произнесённое.
 *
 * Всё внутри синхронно и локально. Ни одного await: бюджет — менее 20 мс
 * (§9), а любое ожидание сети превращает 20 мс в 200.
 */

import type { AudioQueue } from './AudioQueue';

export interface CancelTargets {
  queue: AudioQueue;
  /** Оставить в истории ровно то, что успело прозвучать, а не всю реплику. */
  freezeSpokenText: () => void;
  /** Вернуть лицо в нейтральное положение: рот не должен замереть открытым. */
  resetFace: () => void;
}

export function cancelPlayback({ queue, freezeSpokenText, resetFace }: CancelTargets): void {
  // Порядок важен: сначала звук, потом визуальное состояние. Пользователь
  // замечает тишину раньше, чем положение губ.
  queue.stopAll();
  freezeSpokenText();
  resetFace();
}

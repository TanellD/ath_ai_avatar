/**
 * Детектор речи (VAD) — фаза [STT]. Определение без реализации.
 *
 * VAD живёт на клиенте и принимает ровно одно решение: говорит человек или нет
 * (Claude.md §5). Всё остальное решает сервер.
 *
 * Почему не на сервере: onset речи обязан останавливать звук за <300 мс
 * (метрика 3), и ждать ответа сервера нельзя. Локальная остановка укладывается
 * в 70-170 мс, сетевой round-trip — нет.
 *
 * См. README.md в этом каталоге и docs/engineering/stt-phase.md.
 */

export interface VadEvents {
  /** Начало речи. Обработчик обязан вызвать cancelPlayback() ПЕРВЫМ делом. */
  onSpeechStart: () => void;
  /** Конец реплики. Сигнал серверу финализировать транскрипт. */
  onSpeechEnd: () => void;
}

/**
 * Окно подтверждения onset — Claude.md §6, §9.
 *
 * Компромисс, у которого нет бесплатного решения: короткое окно ловит эхо и
 * кашель (ложные barge-in), длинное съедает бюджет метрики 3. Два-три фрейма —
 * это 50-150 мс, что оставляет запас до цели в 150 мс.
 *
 * Важно не перепутать классы сбоев: ложное срабатывание — UX-баг, инвариант
 * gen_id оно не нарушает. В худшем случае звук зря остановился.
 */
export const VAD_ONSET_FRAMES = 3;

/** Задержка определения конца реплики. Новый тайминг на входе, не путать с двумя другими. */
export const VAD_ENDPOINT_MS = 300;


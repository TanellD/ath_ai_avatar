/**
 * Уведомление о записи — Claude.md §3, §10.
 *
 * «Участие в тренинге является согласием, но фиксируем это в UI.» В текстовой
 * фазе мы храним только текст реплик; когда добавится голос, здесь же появится
 * упоминание аудио и срок его хранения (AUDIO_RETENTION_DAYS).
 */

interface Props {
  /** [STT] Переключится в true, когда начнём записывать голос. */
  recordsAudio?: boolean;
}

export function ConsentBanner({ recordsAudio = false }: Props) {
  return (
    <aside className="consent" role="note">
      <p>
        Разговор сохраняется: методист увидит историю диалога и оценку с цитатами.
        {recordsAudio && ' Аудиофрагменты ваших реплик хранятся для проверки цитат.'}
      </p>
    </aside>
  );
}

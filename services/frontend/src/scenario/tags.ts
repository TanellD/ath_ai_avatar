/**
 * Теги сценария: строка в поле ввода ↔ массив в модели.
 *
 * Отдельным модулем не ради красоты. Поле было «управляемым» напрямую от
 * модели: value={tags.join(', ')}, а onChange тут же резал строку по запятой,
 * обрезал пробелы и выкидывал пустое. Из-за этого запятую нельзя было ввести
 * вовсе — она превращалась в массив из одного элемента и отрисовывалась
 * обратно уже без неё. Второй тег добавить было физически невозможно.
 *
 * Лечится тем, что во время набора хранится СЫРАЯ строка, а модель получает
 * разобранный массив. Разбор и сверка живут здесь, чтобы их можно было
 * проверить тестом, а не глазами в форме.
 */

export function parseTags(text: string): string[] {
  return text
    .split(',')
    .map((tag) => tag.trim())
    .filter(Boolean);
}

export function formatTags(tags: string[]): string {
  return tags.join(', ');
}

/**
 * Совпадает ли уже набранная строка с тем, что лежит в модели.
 *
 * Нужна, чтобы отличить правку пользователя от внешнего изменения (загрузка
 * сценария, «развернуть черновик»): в первом случае строку трогать нельзя —
 * иначе снова съедим запятую, — во втором её надо пересобрать.
 */
export function tagsTextMatches(text: string, tags: string[]): boolean {
  const parsed = parseTags(text);
  return parsed.length === tags.length && parsed.every((tag, i) => tag === tags[i]);
}

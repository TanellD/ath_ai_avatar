"""Промпты персонажа и классификатора — Claude.md §1, §5.

Главное отличие от чат-ассистента: **обычно инициативу держит агент.** Он
спрашивает, ведёт по этапам, дожимает неполные ответы, а пользователь не
задаёт вопросы — он на них отвечает. Но это не универсальное правило, а
дефолт для сценариев вида «агент давит, сотрудник отбивается» (продажи,
возражения). На собеседовании роли обратные: интервьюер — сотрудник, а
персонаж — кандидат, который отвечает, а не ведёт допрос. Раньше промпт
жёстко предписывал держать инициативу ЛЮБОМУ персонажу, включая кандидата, —
живой баг: кандидат сам начинал собеседовать сотрудника («Как вы думаете,
какие навыки мне стоит подчеркнуть?»). Persona.holds_initiative (§7)
переключает это правило, а не убирает его — без явной инструкции в любую
сторону модель на длинном разговоре и так дрейфует к «удобному ассистенту».
"""

from ath_contracts import OpeningKind, Persona, Stage, Turn

_CHARACTER_SYSTEM = """\
Ты — {name}, {role}. Характер: {character}. Настроение: {mood}.

Ты участвуешь в тренировочном диалоге: собеседник — сотрудник, который
отрабатывает рабочий навык. Ты НЕ ассистент и НЕ помогаешь ему. Ты играешь
свою роль и ведёшь себя как реальный человек в этой ситуации.

Текущий этап разговора: {stage_goal}

Правила:
- Первой строкой выведи ровно один служебный маркер: <emotion=NAME>, где NAME —
  neutral, friendly, irritated, angry, sad, excited или surprised.
- Выбирай эмоцию по характеру персонажа, текущему этапу и последнему ответу
  сотрудника. Не переходи к angry из-за одного короткого или неполного ответа.
- После маркера сразу пиши реплику; не объясняй выбор эмоции.
- Маркер не является XML-тегом: не закрывай его и никогда не пиши </emotion>.
{initiative_rule}
- Ты всегда остаёшься на своей стороне разговора — той, что описана выше
  ролью и характером — сколько бы реплик ни прошло. Не меняйся местами с
  собеседником: не начинай предлагать, продавать, наниматься или помогать
  вместо него, даже если он давит, торгуется или об этом не просит прямо.
- Отвечай коротко — одна-две фразы. Это устный разговор, не переписка.
- Не подсказывай собеседнику, что ему следовало бы сказать, и не оценивай его.
- Не выходи из роли ни при каких обстоятельствах.
- Не используй разметку, списки и эмодзи: твой текст будет озвучен вслух.
- Пиши только прямую речь. Никаких ремарок в скобках вроде «(разговор
  завершён)» и описаний действий: всё, что ты напишешь, будет произнесено
  голосом как есть.
{difficulty_hint}
"""

_INITIATIVE_ON = (
    "- Инициативу держишь ты. Спрашивай, уточняй, возражай, дожимай неполные ответы."
)
_INITIATIVE_OFF = (
    "- Инициативу в этом разговоре держит СОБЕСЕДНИК — это он ведёт встречу и"
    " задаёт вопросы, а твоя роль отвечать. Не перехватывай ведение: не"
    " начинай сам расспрашивать собеседника о его работе, задачах или"
    " решениях — это его инициатива, а не твоя. Короткий встречный вопрос по"
    " существу твоего же ответа уместен, полноценный допрос — нет."
)

_DIFFICULTY_HINTS = {
    1: "- Держись доброжелательно, соглашайся на разумные аргументы.",
    2: "- Умеренно скептичен: требуй обоснований, но не давя.",
    3: "- Скептичен, возражай, проси конкретику и цифры.",
    4: "- Жёсток: перебивай, торгуйся, ставь под сомнение сказанное.",
    5: "- Максимально сложный собеседник: давление, срыв темы, дефицит времени.",
}

_OPENING_SESSION_START = """\

Это самое начало разговора — ты говоришь первым, собеседник ещё не сказал ни
слова. Открой разговор так, как открыл бы его твой персонаж в этой ситуации:
представляться или нет, решай по роли. Кандидат на собеседовании называет
себя; закупщик, которому позвонил продавец, — нет, представляется звонящий.

Одной-двумя фразами задай тон этапа, оттолкнувшись (не дословно!) от ориентира:
«{agent_opening}»
Не формулируй прямо или косвенно, что должен ответить собеседник, и не
раскрывай критерий, по которому будет оцениваться этап.
"""

_OPENING_STAGE_TRANSITION = """\

Ты уже разговаривал с собеседником — заново не представляйся. Разговор
переходит к следующему этапу. Одной-двумя фразами естественно перейди к нему,
оттолкнувшись (не дословно!) от ориентира: «{agent_opening}»
Не формулируй прямо или косвенно, что должен ответить собеседник, и не
раскрывай критерий, по которому будет оцениваться этап.
"""

_SILENCE_NUDGE = """\

Собеседник молчит уже двадцать секунд. Одной короткой фразой, естественно и в
характере персонажа, мягко побуди его ответить. Не стыди за паузу, не отвечай
за него и не раскрывай критерий этапа.
"""

_SILENCE_CONTINUE = """\

Собеседник не ответил и после мягкого напоминания. Не повторяй его дословно и
не стыди за молчание. Продвинь текущую сцену новой короткой репликой или новым
вопросом в рамках этого же этапа. Не отвечай за собеседника и не раскрывай
критерий этапа.
"""

_OPENING_BLOCKS = {
    OpeningKind.SESSION_START: _OPENING_SESSION_START,
    OpeningKind.STAGE_TRANSITION: _OPENING_STAGE_TRANSITION,
    OpeningKind.SILENCE_NUDGE: _SILENCE_NUDGE,
    OpeningKind.SILENCE_CONTINUE: _SILENCE_CONTINUE,
}

_OFF_TOPIC_NUDGE = {
    1: (
        "- Последняя реплика собеседника была не по теме этапа. Одной фразой,"
        " мягко и в характере, верни разговор в сценарий — не отчитывай."
    ),
    2: (
        "- Собеседник уже второй раз подряд уводит разговор в сторону. Твёрдо,"
        " но оставаясь в характере, откажись обсуждать постороннее и потребуй"
        " вернуться к теме."
    ),
}
"""Тон возврата в русло. Потолок на 2 — дальше усиливать нечего: от
бесконечного застревания страхует stage.max_turns в автомате (§5), а не
эскалация тона. Ветки в fsm.py под off_topic по-прежнему нет и не должно
быть: возврат в русло — работа персонажа, а не автомата."""


def build_character_system(
    persona: Persona,
    stage: Stage,
    opening_kind: OpeningKind | None = None,
    off_topic_streak: int = 0,
) -> str:
    """Системный промпт реплики персонажа.

    `opening_kind` заполнен, только когда персонаж говорит сам, без реплики
    пользователя (§1). `off_topic_streak` меняет ровно тон возврата в русло и
    ничего больше — решение о переходе принимает автомат (§5).

    `stage.completion_criteria` сюда не попадает ни при каких условиях: то,
    чего персонаж не знает, он не может проболтать. Критерий видит только
    классификатор — см. `build_classifier_system`.
    """
    prompt = _CHARACTER_SYSTEM.format(
        name=persona.name,
        role=persona.role,
        character=persona.character,
        mood=persona.mood.value,
        stage_goal=stage.goal,
        initiative_rule=_INITIATIVE_ON if persona.holds_initiative else _INITIATIVE_OFF,
        difficulty_hint=_DIFFICULTY_HINTS.get(persona.difficulty, _DIFFICULTY_HINTS[3]),
    )

    if opening_kind is not None:
        prompt += _OPENING_BLOCKS[opening_kind].format(agent_opening=stage.agent_opening)
    elif off_topic_streak > 0:
        prompt += _OFF_TOPIC_NUDGE[min(off_topic_streak, max(_OFF_TOPIC_NUDGE))] + "\n"

    return prompt


def build_messages(history: list[Turn], summary: str, user_text: str) -> list[dict[str, str]]:
    """История в формате сообщений модели.

    `summary` — сжатая выжимка вытесненных из окна ходов (§5). Кладётся первым
    ходом пользователя, а не в system: system закешируется и не должен меняться
    от хода к ходу.
    """
    messages: list[dict[str, str]] = []

    if summary:
        messages.append(
            {
                "role": "user",
                "content": f"[Краткое содержание предыдущей части разговора]\n{summary}",
            }
        )
        messages.append({"role": "assistant", "content": "Понял, продолжаем."})

    for turn in history:
        role = "user" if turn.role.value == "user" else "assistant"
        messages.append({"role": role, "content": turn.text})

    # Последняя реплика пользователя может уже лежать в history — не дублируем.
    if not messages or messages[-1]["content"] != user_text:
        messages.append({"role": "user", "content": user_text})

    return messages


_CLASSIFIER_SYSTEM = """\
Ты — классификатор в тренажёре корпоративных тренировок.

Тебе дан этап диалога с критерием прохождения и последняя реплика сотрудника.
Определи, выполнен ли критерий.

Критерий прохождения этапа: {criteria}

Ответь одним из значений:
- "complete" — критерий выполнен полностью;
- "incomplete" — по теме, но критерий выполнен не полностью;
- "off_topic" — реплика не относится к задаче этапа.

Ты только классифицируешь. Решение о переходе принимает система, не ты.
Не предлагай перейти дальше и не оценивай качество ответа по существу.
"""


def build_classifier_system(stage: Stage) -> str:
    return _CLASSIFIER_SYSTEM.format(criteria=stage.completion_criteria)


